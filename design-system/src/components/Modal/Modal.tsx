import type { ReactElement } from 'react';
import type { ModalOverlayProps } from 'react-aria-components';
import { Modal as AriaModal, ModalOverlay } from 'react-aria-components';

import type { DataAttributes } from '#shared/types';
import { modalRecipe } from '#styled-system/recipes';

import { CloseButton, type CloseButtonProps } from '../CloseButton';
import { ButtonFixWrongCapturingContext } from '../shared';

export interface ModalProps extends ModalOverlayProps, DataAttributes {
  hideCloseButton?: boolean;
  closeButtonProps?: CloseButtonProps;
}

/**
 * Модальное окно – это наложенный элемент, который блокирует взаимодействие с элементами за его пределами.
 *
 * ## Использование
 *
 * Модальные окна часто используются для отображения важной информации, сбора пользовательского ввода или подтверждения действия перед его выполнением. Вот несколько распространённых сценариев использования компонентов модальных окон:
 *
 * - **Формы и ввод**: Предложите пользователям заполнить формы или предоставить дополнительный ввод.
 * - **Диалоги подтверждения**: Подтвердите действия, которые могут иметь значительные последствия, такие как удаление данных.
 *
 * Модальное окно динамически подстраивает свой размер в зависимости от ширины содержимого, обеспечивая гибкость для различных типов содержимого. Оно адаптивно к различным размерам экрана, включает прокрутку для переполненного содержимого и устанавливает максимальный предел ширины, чтобы поддерживать читаемость. Это гарантирует, что модальное окно остаётся удобным и визуально привлекательным на различных устройствах.
 *
 * ### Настройка
 *
 * Модальные окна можно настраивать в соответствии с дизайном и брендингом вашего приложения. Вы можете стилизовать наложение, заголовок, тело и элементы нижнего колонтитула, чтобы они соответствовали вашему UI-дизайну. Кроме того, вы можете добавить пользовательские анимации, переходы или эффекты, чтобы улучшить пользовательский опыт.
 *
 * - `isDismissable={true}`: Позволяет пользователю кликнуть за пределами модального окна или нажать клавишу Escape, чтобы закрыть его.
 * - `hideCloseButton={true}`: Скрывает кнопку закрытия внутри модального окна при необходимости.
 * - `closeButtonProps`: Пробрасывает произвольные пропсы на встроенную кнопку закрытия (крестик). Полезно для разметки кнопки `data-*` атрибутами под аналитику или для переопределения `aria-label`. Не применяется, если кнопка закрытия скрыта через `hideCloseButton`.
 *
 * ## Лучшие практики
 *
 * При использовании модальных окон в вашем приложении учитывайте следующие лучшие практики:
 *
 * - **Доступность**: Убедитесь, что модальные окна доступны пользователям с ограниченными возможностями. Это включает навигацию с клавиатуры, совместимость со считывателями экранов и правильное управление фокусом.
 * - **Производительность**: Обратите внимание на влияние производительности модальных окон, особенно на мобильных устройствах. Избегайте чрезмерных анимаций или сложных макетов, которые могут замедлить пользовательский опыт.
 * - **Пользовательский опыт**: Разрабатывайте модальные окна так, чтобы они были интуитивно понятными и простыми в использовании. Избегайте перегруженности пользователей слишком большим количеством информации или ненужными функциями.
 *
 * ## Специфика
 *
 * CSS-переменная `--visual-viewport-height` может использоваться для установки высоты ModalOverlay, что позволяет учитывать виртуальную клавиатуру на мобильных устройствах.
 *
 * ```css
 *  .modalOverlay {
 *   position: fixed;
 *   height: var(--visual-viewport-height);
 * }```
 *
 * ## Особенности
 *
 * - **Стилизация**: Включает анимации входа и выхода для лёгкой стилизации. Настраиваемые элементы подложки и наложения.
 * - **Доступность**: Скрывает содержимое за пределами модального окна от вспомогательных технологий, когда оно открыто. При желании закрывается при взаимодействии или нажатии клавиши Escape.
 * - **Управление фокусом**: Перемещает фокус внутрь модального окна при монтировании и восстанавливает его при размонтировании. Фокус остаётся внутри модального окна, предотвращая перемещение табуляции за его пределы.
 * - **Блокировка прокрутки**: Предотвращает прокрутку страницы за пределами модального окна, включая мобильные браузеры.
 *
 * Примечание: Модальное окно предоставляет только наложение. Комбинируйте с диалогом для полностью доступных модальных диалогов. Другие наложения, такие как меню, также могут использоваться в модальном наложении.
 * [Ссылка на документацию Modal](https://react-spectrum.adobe.com/react-aria/Modal.html#modal)
 */

export function Modal(props: ModalProps): ReactElement {
  const { children, hideCloseButton, closeButtonProps, ...overlayProps } =
    props;
  const classes = modalRecipe();

  return (
    <ModalOverlay {...overlayProps} className={classes.overlay}>
      <div className={classes.rootWrapper}>
        <AriaModal className={classes.root}>
          {(renderProps) => (
            <ButtonFixWrongCapturingContext.Provider
              value={{ fixWrongCapturing: true }}
            >
              {!hideCloseButton && (
                <CloseButton
                  {...closeButtonProps}
                  onPress={renderProps.state.close}
                  size="lg"
                />
              )}
              {typeof children === 'function'
                ? children(renderProps)
                : children}
            </ButtonFixWrongCapturingContext.Provider>
          )}
        </AriaModal>
      </div>
    </ModalOverlay>
  );
}
